// App-wide constants and paths.

import path from 'node:path';

export const platform = process.platform;
export const isMac = platform === 'darwin';
export const isWin = platform === 'win32';

/** How often the clipboard is checked for new text. */
export const POLL_MS = 500;
/** Recent clips listed directly in the tray menu. */
export const TRAY_MENU_ITEMS = 10;
/** Wait for focus to return to the previous app before sending the paste keystroke. */
export const PASTE_DELAY_MS = isMac ? 180 : 100;

export const POPUP_SIZE = { width: 560, height: 460 };
export const THEME_BACKGROUND = { light: '#fbfbfd', dark: '#17171b' };

/**
 * Clipboard formats that password managers add to say "don't record this":
 * nspasteboard.org markers on macOS, Windows' clipboard-history exclusion formats,
 * and KDE's password hint on Linux.
 */
export const CONCEALED_FORMATS = isMac
  ? ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType']
  : isWin
    ? ['ExcludeClipboardContentFromMonitorProcessing', 'Clipboard Viewer Ignore']
    : ['x-kde-passwordManagerHint'];

const root = path.resolve(import.meta.dirname, '..', '..');
export const paths = {
  preload: path.join(root, 'src', 'preload.cjs'),
  page: path.join(root, 'src', 'renderer', 'index.html'),
  appIcon: path.join(root, 'assets', 'icon.png'),
  trayIcon: path.join(root, 'assets', isMac ? 'trayTemplate.png' : 'tray.png'),
};
